#!/usr/bin/env bash
# Rewrites prisma/migrations/0_baseline from prisma/schema.prisma. Needs no database.
# Only valid before the baseline is applied anywhere; afterwards every change is a new migration.
set -euo pipefail
cd "$(dirname "$0")/../.."

out=prisma/migrations/0_baseline/migration.sql
mkdir -p "$(dirname "$out")"
plan=$(DIRECT_URL=postgresql://none@localhost:1/none node_modules/.bin/prisma migrate diff \
  --from-empty --to-schema prisma/schema.prisma --script)

{
  printf '%s\n' "-- Generated by scripts/db/generate-baseline.sh from prisma/schema.prisma." \
    "BEGIN;" "SET LOCAL lock_timeout = '3s';" ""
  printf '%s\n' "$plan"
  printf '\n%s\n' "COMMIT;"
} > "$out"

lock=prisma/migrations/migration_lock.toml
test -f "$lock" || printf '%s\n' \
  '# Please do not edit this file manually' \
  '# It should be added in your version-control system (e.g., Git)' \
  'provider = "postgresql"' > "$lock"

echo "wrote $out ($(grep -c '^CREATE TABLE' "$out") tables, $(grep -c '^CREATE TYPE' "$out") types)"

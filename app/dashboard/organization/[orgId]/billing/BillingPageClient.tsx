// ---------------------------------------------------------------------------
// Zod schemas — narrow API responses at the network boundary so the rest
// of the component can rely on inferred types instead of `as` casts.
// ---------------------------------------------------------------------------

const billingSummarySchema = z.object({
  fundingSource: z
    .enum(["PERSONAL", "WALLET", "INVOICE", "LICENSE", "PROJECT"])
    .nullable(),
  monthToDate: z.object({
    gross: z.number(),
    paymentCount: z.number(),
  }),
  outstanding: z.object({
    amount: z.number(),
    invoiceCount: z.number(),
  }),
  pendingCharges: z
    .object({ amount: z.number(), paymentCount: z.number() })
    .nullable(),
  paymentTermsDays: z.number(),
});
type BillingSummary = z.infer<typeof billingSummarySchema>;

const orgInvoiceSchema = z.object({
  id: z.string(),
  invoiceNumber: z.string(),
  totalPaise: z.number(),
  displayCurrency: z.string(),
  status: z.enum([
    "DRAFT",
    "ISSUED",
    "PAID",
    "OVERDUE",
    "VOID",
    "CANCELLED",
  ]),
  dueDate: z.string().nullable(),
  paidAt: z.string().nullable(),
  autoGenerated: z.boolean(),
  createdAt: z.string(),
});

const invoicesListResponseSchema = z.object({
  data: z.array(orgInvoiceSchema).default([]),
});

const invoicePayResponseSchema = z.object({
  razorpayOrderId: z.string().startsWith("order_"),
  keyId: z.string().min(1),
  amountPaise: z.number().int().positive(),
  currency: z.string().length(3),
  invoice: z.object({
    id: z.string(),
    invoiceNumber: z.string(),
    status: z.string(),
  }),
});
type InvoicePayResponse = z.infer<typeof invoicePayResponseSchema>;

// The per-invoice GET endpoint returns the full invoice + relations,
// but for the post-checkout poll we only care about `status`. Zod
// strips unknown fields by default so this narrow schema accepts the
// full payload and just lifts the one field we need.
const invoiceStatusPollSchema = z.object({
  invoice: z.object({
    status: z.enum([
      "DRAFT",
      "ISSUED",
      "PAID",
      "OVERDUE",
      "VOID",
      "CANCELLED",
    ]),
  }),
});

// Same poll budget as the wallet flow (see credits/page.tsx) — 20s
// total, then we fall back to "awaiting confirmation" so the UI never
// stalls if Razorpay's webhook is slow.
const INVOICE_POLL_INTERVAL_MS = 1000;
const INVOICE_POLL_MAX_ATTEMPTS = 20;

// Discriminated union for the post-checkout flow:
//   - "confirmed": webhook landed within the poll budget; row is PAID.
//   - "pending":   capture succeeded but the webhook is slow.
//   - "not_paid":  popup dismissed or `payment.failed` fired (already
//      toasted); the success handler stays silent.
type InvoicePayMutationResult =
  | { result: InvoicePayResponse; outcome: "confirmed" }
  | { result: InvoicePayResponse; outcome: "pending" }
  | { result: InvoicePayResponse; outcome: "not_paid" };

async function fetchBilling(orgId: string): Promise<BillingSummary> {
  const res = await fetch(`/api/organizations/${orgId}/billing`);
  return parseJsonResponse(
    res,
    billingSummarySchema,
    "Failed to load billing summary",
  );
}

async function fetchInvoices(orgId: string) {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices?perPage=50`,
  );
  const parsed = await parseJsonResponse(
    res,
    invoicesListResponseSchema,
    "Failed to load invoices",
  );
  return { invoices: parsed.data };
}

async function generateInvoice(orgId: string) {
  const res = await fetch(
    `/api/organizations/${orgId}/billing/generate-invoice`,
    { method: "POST" },
  );
  const body = await res.json().catch(() => null);
  if (!res.ok) throw new Error(errorMessageFromBody(body, "Failed to generate invoice"));
  return body;
}

async function payInvoice(
  orgId: string,
  invoiceId: string,
): Promise<InvoicePayResponse> {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices/${invoiceId}/pay`,
    { method: "POST" },
  );
  return parseJsonResponse(
    res,
    invoicePayResponseSchema,
    "Failed to initiate payment",
  );
}

async function fetchInvoiceStatus(
  orgId: string,
  invoiceId: string,
): Promise<"DRAFT" | "ISSUED" | "PAID" | "OVERDUE" | "VOID" | "CANCELLED" | null> {
  const res = await fetch(
    `/api/organizations/${orgId}/billing-account/invoices/${invoiceId}`,
  );
  if (!res.ok) return null;
  // Status poll runs in a tight loop; tolerate a transient
  // contract-drift parse failure rather than throwing the loop —
  // worst case we keep polling until the budget elapses.
  const parsed = invoiceStatusPollSchema.safeParse(await res.json());
  return parsed.success ? parsed.data.invoice.status : null;
}

/**
 * Poll the invoice endpoint until the webhook flips `status` to
 * `PAID` or the budget elapses. Returns `true` on confirmation,
 * `false` on timeout. The webhook handler (`handleOrgPaymentSuccess`)
 * is the source of truth — this exists purely so the UI doesn't lie
 * about state for ~5–20s after a successful capture.
 */
async function pollInvoiceUntilPaid(
  orgId: string,
  invoiceId: string,
): Promise<boolean> {
  for (let attempt = 0; attempt < INVOICE_POLL_MAX_ATTEMPTS; attempt++) {
    const status = await fetchInvoiceStatus(orgId, invoiceId);
    if (status === "PAID") return true;
    await new Promise((r) => setTimeout(r, INVOICE_POLL_INTERVAL_MS));
  }
  return false;
}

export function BillingPageClient({ orgId }: { orgId: string }) {
  const { isAtLeast } = useOrgRole(orgId);
  const { allowed } = useRequireOrgAccess(orgId, {
    minRole: "MANAGER",
    canSponsor: true,
  });
  const searchParams = useSearchParams();
  const initialTab = searchParams?.get("tab") === "wallet" ? "wallet" : "invoices";
  const { data: session } = useSession();
  const queryClient = useQueryClient();

  const summary = useQuery({
    queryKey: ["org-billing", orgId],
    queryFn: () => fetchBilling(orgId),
    // Gate on role+capability so non-billable or non-MANAGER users
    // don't trigger a 403 before the redirect.
    enabled: allowed,
  });
  const invoices = useQuery({
    queryKey: ["org-billing-invoices", orgId],
    queryFn: () => fetchInvoices(orgId),
    enabled: allowed,
  });

  const generateMutation = useMutation({
    mutationFn: () => generateInvoice(orgId),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["org-billing", orgId] });
      queryClient.invalidateQueries({
        queryKey: ["org-billing-invoices", orgId],
      });
    },
  });

  const { toast } = useToast();

  const payMutation = useMutation({
    mutationFn: async (
      invoiceId: string,
    ): Promise<InvoicePayMutationResult> => {
      const result = await payInvoice(orgId, invoiceId);

      const loaded = await loadScript(
        "https://checkout.razorpay.com/v1/checkout.js",
      ).catch(() => false);
      if (!loaded || !window.Razorpay) {
        throw new Error(
          "Razorpay checkout failed to load. Please disable ad-blockers and retry.",
        );
      }

      // The popup resolves with `paid: true` only if Razorpay's
      // `handler` fired (capture succeeded). Otherwise we treat the
      // attempt as not-yet-paid and skip polling — the row stays
      // ISSUED, no false "awaiting confirmation" toast.
      const prefill = buildRazorpayPrefill({
        name: session?.user?.name ?? null,
        email: session?.user?.email ?? null,
        phone: session?.user?.phone ?? null,
      });
      const paid = await new Promise<boolean>((resolve) => {
        const rzp = new window.Razorpay({
          key: result.keyId,
          amount: result.amountPaise,
          currency: result.currency,
          name: "Familiarise",
          description: `Invoice ${result.invoice.invoiceNumber}`,
          order_id: result.razorpayOrderId,
          ...(Object.keys(prefill).length > 0 ? { prefill } : {}),
          handler: () => {
            resolve(true);
          },
          theme: { color: "#2563EB" },
        });
        rzp.on("payment.failed", () => {
          toast({
            title: "Payment failed",
            description:
              "Your card was declined or the payment timed out. Please try again.",
            variant: "destructive",
          });
          resolve(false);
        });
        rzp.open();
      });

      if (!paid) {
        // Either payment.failed fired (already toasted) or the user
        // dismissed the popup. Skip polling and let the caller show
        // nothing extra.
        return { result, outcome: "not_paid" };
      }

      // Bridge the webhook-settlement race so the row flips to PAID
      // without the user manually refreshing. `outcome === "pending"`
      // means the budget elapsed; the capture is still safe (webhook
      // is idempotent on `OrganizationInvoice.providerOrderId`).
      const confirmed = await pollInvoiceUntilPaid(orgId, invoiceId);
      return { result, outcome: confirmed ? "confirmed" : "pending" };
    },
    onSuccess: ({ result, outcome }) => {
      queryClient.invalidateQueries({
        queryKey: ["org-billing-invoices", orgId],
      });
      queryClient.invalidateQueries({
        queryKey: ["org-billing", orgId],
      });
      if (outcome === "confirmed") {
        toast({
          title: "Invoice paid",
          description: `Invoice ${result.invoice.invoiceNumber} is now marked as PAID.`,
        });
      } else if (outcome === "pending") {
        toast({
          title: "Payment received",
          description:
            "Awaiting confirmation from Razorpay. The invoice will flip to PAID once the webhook lands.",
        });
      }
      // outcome === "not_paid" — payment.failed already toasted, or
      // the user dismissed the popup; stay silent.
    },
    onError: (err) => {
      toast({
        title: "Payment could not be initiated",
        description: err instanceof Error ? err.message : String(err),
        variant: "destructive",
      });
    },
  });

  // Manual invoice composer state
  const [showComposer, setShowComposer] = useState(false);
  const [lineItems, setLineItems] = useState([
    { description: "", quantity: 1, unitPrice: "" },
  ]);
  const [taxRate, setTaxRate] = useState("");
  const [gstin, setGstin] = useState("");
  const [dueDate, setDueDate] = useState("");
  const [composerError, setComposerError] = useState<string | null>(null);

  if (!allowed) return null;

  async function createInvoice() {
    setComposerError(null);
    const items = lineItems
      .filter((li) => li.description.trim())
      .map((li) => ({
        description: li.description.trim(),
        quantity: li.quantity,
        unitPrice: Math.round(parseFloat(li.unitPrice || "0") * 100),
      }));
    if (items.length === 0) {
      setComposerError("Add at least one line item.");
      return;
    }
    const res = await fetch(`/api/organizations/${orgId}/billing-account/invoices`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        items,
        // Default due date: 60 days from today (NET-60) if not supplied.
        dueDate: dueDate || new Date(Date.now() + 60 * 24 * 60 * 60 * 1000).toISOString(),
        issueImmediately: true,
      }),
    });
    const body = await res.json();
    if (!res.ok) {
      setComposerError(errorMessageFromBody(body, "Failed to create invoice"));
      return;
    }
    queryClient.invalidateQueries({ queryKey: ["org-billing-invoices", orgId] });
    setShowComposer(false);
    setLineItems([{ description: "", quantity: 1, unitPrice: "" }]);
  }

  return (
    <>
      <DashboardHeader
        title="Billing"
        subtitle="Invoices, charges, and outstanding balance"
        actions={
          <div className="flex gap-2">
            {isAtLeast("OWNER") && (
              <Button size="sm" variant="outline" onClick={() => setShowComposer(true)}>
                <Plus className="h-4 w-4 mr-1" /> Create invoice
              </Button>
            )}
            {isAtLeast("OWNER") &&
              summary.data?.fundingSource === "INVOICE" && (
              <Button
                size="sm"
                onClick={() => generateMutation.mutate()}
                disabled={generateMutation.isPending}
              >
                <Sparkles className="h-4 w-4 mr-1" /> Generate invoice
              </Button>
            )}
          </div>
        }
      />
      <DashboardContent>
        <Tabs defaultValue={initialTab}>
          <TabsList>
            <TabsTrigger value="invoices">Invoices</TabsTrigger>
            <TabsTrigger value="wallet">Wallet</TabsTrigger>
          </TabsList>

          <TabsContent value="invoices" className="space-y-6">
            {summary.isLoading ? (
              <p className="text-sm text-zinc-500">Loading…</p>
            ) : (
              <DashboardGrid columns={4}>
                <StatCard
                  title="This month gross"
                  value={formatCurrencyAmount(
                    summary.data?.monthToDate.gross ?? 0,
                    "INR",
                  )}
                  subtitle={`${summary.data?.monthToDate.paymentCount ?? 0} bookings`}
                  icon={CreditCard}
                  variant="success"
                />
                <StatCard
                  title="Outstanding"
                  value={formatCurrencyAmount(
                    summary.data?.outstanding.amount ?? 0,
                    "INR",
                  )}
                  subtitle={`${summary.data?.outstanding.invoiceCount ?? 0} invoices`}
                  icon={AlertCircle}
                  variant={
                    (summary.data?.outstanding.invoiceCount ?? 0) > 0
                      ? "warning"
                      : "default"
                  }
                />
                {summary.data?.pendingCharges && (
                  <StatCard
                    title="Pending charges"
                    value={formatCurrencyAmount(
                      summary.data.pendingCharges.amount,
                      "INR",
                    )}
                    subtitle={`${summary.data.pendingCharges.paymentCount} unbilled`}
                    icon={CreditCard}
                  />
                )}
                {/* Payment terms only apply to INVOICE-funded orgs.
                    WALLET orgs pre-fund their balance and have no credit
                    terms; showing NET-60 there is misleading. */}
                {summary.data?.fundingSource !== "WALLET" && (
                  <StatCard
                    title="Payment terms"
                    value={`NET-${summary.data?.paymentTermsDays ?? 60}`}
                  />
                )}
                {summary.data?.fundingSource && (
                  <StatCard
                    title="Funding source"
                    value={FUNDING_SOURCE_LABEL[summary.data.fundingSource]}
                  />
                )}
              </DashboardGrid>
            )}

        <Card className="mt-6">
          <CardHeader>
            <CardTitle className="text-base">Invoices</CardTitle>
            <CardDescription>
              Manual + auto-generated invoices for this organization.
            </CardDescription>
          </CardHeader>
          <CardContent>
            {invoices.isLoading ? (
              <p className="text-sm text-zinc-500">Loading…</p>
            ) : (
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>Number</TableHead>
                    <TableHead>Amount</TableHead>
                    <TableHead>Status</TableHead>
                    <TableHead>Due</TableHead>
                    <TableHead className="w-24"></TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {invoices.data?.invoices.map((inv) => (
                    <TableRow key={inv.id}>
                      <TableCell className="font-mono text-xs">
                        {inv.invoiceNumber}
                      </TableCell>
                      <TableCell>
                        {formatCurrencyAmount(inv.totalPaise, inv.displayCurrency)}
                      </TableCell>
                      <TableCell>
                        <Badge
                          variant={
                            inv.status === "PAID"
                              ? "default"
                              : inv.status === "OVERDUE"
                                ? "destructive"
                                : "outline"
                          }
                        >
                          {inv.status}
                        </Badge>
                      </TableCell>
                      <TableCell className="text-xs text-zinc-500">
                        {inv.dueDate
                          ? new Date(inv.dueDate).toLocaleDateString()
                          : "—"}
                      </TableCell>
                      <TableCell>
                        {/* Pay is gated to OWNER on the API; mirror that
                            here so non-owners don't see a button that
                            will 403 on click. MAINTAINERs can view the
                            invoice but only the billing owner pays. */}
                        {(inv.status === "ISSUED" ||
                          inv.status === "OVERDUE") &&
                          isAtLeast("OWNER") && (
                            <Button
                              size="sm"
                              variant="outline"
                              onClick={() => payMutation.mutate(inv.id)}
                              disabled={payMutation.isPending}
                            >
                              Pay
                            </Button>
                          )}
                      </TableCell>
                    </TableRow>
                  ))}
                  {invoices.data && invoices.data.invoices.length === 0 && (
                    <TableRow>
                      <TableCell
                        colSpan={5}
                        className="text-center text-sm text-zinc-500 py-6"
                      >
                        No invoices yet.
                      </TableCell>
                    </TableRow>
                  )}
                </TableBody>
              </Table>
            )}
          </CardContent>
        </Card>
          </TabsContent>

          <TabsContent value="wallet">
            <WalletTab orgId={orgId} />
          </TabsContent>
        </Tabs>
      </DashboardContent>

      {/* Manual invoice composer dialog */}
      <Dialog open={showComposer} onOpenChange={setShowComposer}>
        <DialogContent className="max-w-lg">
          <DialogHeader>
            <DialogTitle>Create manual invoice</DialogTitle>
          </DialogHeader>
          <div className="space-y-4">
            <div className="space-y-2">
              <Label>Line items</Label>
              {lineItems.map((li, i) => (
                <div key={i} className="flex gap-2 items-end">
                  <Input
                    placeholder="Description"
                    value={li.description}
                    onChange={(e) => {
                      const next = [...lineItems];
                      next[i] = { ...next[i], description: e.target.value };
                      setLineItems(next);
                    }}
                    className="flex-1"
                  />
                  <Input
                    placeholder="Qty"
                    type="number"
                    min={1}
                    value={li.quantity}
                    onChange={(e) => {
                      const next = [...lineItems];
                      next[i] = { ...next[i], quantity: parseInt(e.target.value) || 1 };
                      setLineItems(next);
                    }}
                    className="w-16"
                  />
                  <Input
                    placeholder="Price (INR)"
                    type="number"
                    min={0}
                    step="0.01"
                    value={li.unitPrice}
                    onChange={(e) => {
                      const next = [...lineItems];
                      next[i] = { ...next[i], unitPrice: e.target.value };
                      setLineItems(next);
                    }}
                    className="w-28"
                  />
                  {lineItems.length > 1 && (
                    <Button
                      variant="ghost"
                      size="icon"
                      onClick={() =>
                        setLineItems(lineItems.filter((_, j) => j !== i))
                      }
                    >
                      <Trash2 className="h-4 w-4 text-red-400" />
                    </Button>
                  )}
                </div>
              ))}
              <Button
                variant="outline"
                size="sm"
                onClick={() =>
                  setLineItems([...lineItems, { description: "", quantity: 1, unitPrice: "" }])
                }
              >
                <Plus className="h-4 w-4 mr-1" /> Add line
              </Button>
            </div>

            <div className="grid grid-cols-2 gap-4">
              <div className="space-y-2">
                <Label htmlFor="inv-tax">Tax rate (0-1)</Label>
                <Input
                  id="inv-tax"
                  type="number"
                  min="0"
                  max="1"
                  step="0.01"
                  value={taxRate}
                  onChange={(e) => setTaxRate(e.target.value)}
                  placeholder="e.g., 0.18"
                />
              </div>
              <div className="space-y-2">
                <Label htmlFor="inv-gstin">GSTIN</Label>
                <Input
                  id="inv-gstin"
                  value={gstin}
                  onChange={(e) => setGstin(e.target.value)}
                  placeholder="Optional"
                />
              </div>
            </div>
            <div className="space-y-2">
              <Label htmlFor="inv-due">Due date</Label>
              <Input
                id="inv-due"
                type="date"
                value={dueDate}
                onChange={(e) => setDueDate(e.target.value)}
              />
            </div>
            {composerError && (
              <p className="text-sm text-red-600">{composerError}</p>
            )}
          </div>
          <DialogFooter>
            <Button variant="outline" onClick={() => setShowComposer(false)}>
              Cancel
            </Button>
            <Button onClick={createInvoice}>Create invoice</Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}
